/**
 * `tsconfig.json` is JSON-with-comments. A scaffold's commented tsconfig made
 * the alias linker throw on `JSON.parse`.
 */
import fs from "node:fs";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import linkTsconfigPathsToVite from "../linkTsconfigPathsToVite";
import { parseJsonc } from "../read-jsonc";

describe("parseJsonc", () => {
  it("accepts line and block comments and trailing commas", () => {
    const parsed = parseJsonc(`{
      // compiler settings
      "compilerOptions": { /* inline */ "baseUrl": ".", "paths": { "app/*": ["src/app/*",], }, },
    }`);

    expect(parsed).toEqual({ compilerOptions: { baseUrl: ".", paths: { "app/*": ["src/app/*"] } } });
  });

  it("keeps comment markers and commas that live inside strings", () => {
    expect(parseJsonc(`{ "url": "http://x.test/*y*/", "text": "a,}" }`)).toEqual({
      url: "http://x.test/*y*/",
      text: "a,}",
    });
  });
});

describe("linkTsconfigPathsToVite with a commented tsconfig", () => {
  const fixture = path.join(__dirname, "fixtures", "tsconfig-jsonc-fixture");
  let originalCwd: string;

  beforeEach(() => {
    originalCwd = process.cwd();
    fs.mkdirSync(fixture, { recursive: true });
    fs.writeFileSync(
      path.join(fixture, "tsconfig.json"),
      `{
  // Generated by create-warlock
  "compilerOptions": {
    "baseUrl": ".",
    "paths": { "app/*": ["src/app/*"], },
  },
}`,
    );
    process.chdir(fixture);
  });

  afterEach(() => {
    process.chdir(originalCwd);
  });

  it("links the paths instead of throwing", () => {
    const aliases = linkTsconfigPathsToVite() as { find: string; replacement: string }[];

    expect(aliases).toHaveLength(1);
    expect(aliases[0].find).toBe("app");
  });
});
